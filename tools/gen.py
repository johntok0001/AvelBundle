#!/usr/bin/env python3
"""Generates the bundle installer definitions from plugins.json.

    gen.py mac     <art-dir> <out-dir>   -> distribution.xml + plugins.tsv
    gen.py windows <art-dir> <out-dir>   -> AvelBundle.iss
    gen.py notes   <art-dir> <out-file>  -> release notes (markdown)

<art-dir> holds one folder per plugin target (e.g. art/AvelTape) with the built
bundles plus version.txt and commit.txt written by the build job.
"""
import json
import os
import sys
from xml.sax.saxutils import escape, quoteattr

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load():
    with open(os.path.join(ROOT, "plugins.json"), encoding="utf-8") as f:
        plugins = json.load(f)
    with open(os.path.join(ROOT, "VERSION"), encoding="utf-8") as f:
        version = f.read().strip()
    return plugins, version


def read(path, default="?"):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read().strip() or default
    except OSError:
        return default


def info(art, p):
    d = os.path.join(art, p["target"])
    return read(os.path.join(d, "version.txt")), read(os.path.join(d, "commit.txt"))


def mac(art, out):
    plugins, version = load()
    os.makedirs(out, exist_ok=True)
    outline, choices, refs, tsv = [], [], [], []
    for p in plugins:
        v, _ = info(art, p)
        pid, name = p["id"], p["product"]
        outline.append(
            f'        <line choice="{pid}">\n'
            f'            <line choice="{pid}.vst3"/>\n'
            f'            <line choice="{pid}.au"/>\n'
            f'        </line>')
        choices.append(
            f'    <choice id="{pid}" title={quoteattr(name)} description={quoteattr(p["about"] + " · v" + v)}/>\n'
            f'    <choice id="{pid}.vst3" title="VST3" description="REAPER, Ableton Live, Cubase, Studio One, Bitwig, FL Studio">\n'
            f'        <pkg-ref id="com.avel.{pid}.vst3"/>\n'
            f'    </choice>\n'
            f'    <choice id="{pid}.au" title="Audio Unit" description="Logic Pro, GarageBand, MainStage">\n'
            f'        <pkg-ref id="com.avel.{pid}.au"/>\n'
            f'    </choice>')
        refs.append(
            f'    <pkg-ref id="com.avel.{pid}.vst3" version="{v}" onConclusion="none">{pid}-vst3.pkg</pkg-ref>\n'
            f'    <pkg-ref id="com.avel.{pid}.au" version="{v}" onConclusion="none">{pid}-au.pkg</pkg-ref>')
        tsv.append("\t".join([pid, p["target"], name, v]))

    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<installer-gui-script minSpecVersion="2">
    <title>Avel Bundle {escape(version)}</title>
    <welcome file="welcome.html" mime-type="text/html"/>
    <conclusion file="conclusion.html" mime-type="text/html"/>
    <options customize="allow" require-scripts="false" hostArchitectures="arm64,x86_64"/>
    <domains enable_anywhere="false" enable_currentUserHome="false" enable_localSystem="true"/>

    <choices-outline>
{chr(10).join(outline)}
    </choices-outline>

{chr(10).join(choices)}

{chr(10).join(refs)}
</installer-gui-script>
"""
    with open(os.path.join(out, "distribution.xml"), "w", encoding="utf-8") as f:
        f.write(xml)
    with open(os.path.join(out, "plugins.tsv"), "w", encoding="utf-8") as f:
        f.write("\n".join(tsv) + "\n")


def windows(art, out):
    plugins, version = load()
    os.makedirs(out, exist_ok=True)
    art = os.path.abspath(art)
    comps, files, deletes = [], [], []
    for p in plugins:
        v, _ = info(art, p)
        pid, name = p["id"], p["product"]
        src = os.path.join(art, p["target"], "VST3", name + ".vst3")
        dest = "{commoncf64}\\VST3\\" + name + ".vst3"
        comps.append(f'Name: "{pid}"; Description: "{name} — {p["about"]} (v{v})"; Types: full custom')
        files.append(f'Source: "{src}\\*"; DestDir: "{dest}"; Components: {pid}; '
                     f'Flags: ignoreversion recursesubdirs createallsubdirs')
        deletes.append(f'Type: filesandordirs; Name: "{dest}"; Components: {pid}')

    iss = f"""; Generated by tools/gen.py — do not edit by hand.
#define AppVersion "{version}"

[Setup]
AppId={{{{4F1C7A2E-8B3D-4E59-A6C0-2D9E7B1F5A38}}
AppName=Avel Bundle
AppVersion={{#AppVersion}}
AppVerName=Avel Bundle {{#AppVersion}}
AppPublisher=Avel
AppPublisherURL=https://github.com/johntok0001/AvelBundle
DefaultDirName={{autopf}}\\Avel\\Avel Bundle
DisableDirPage=yes
DisableProgramGroupPage=yes
UninstallDisplayName=Avel Bundle (VST3)
PrivilegesRequired=admin
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
OutputDir={os.path.join(ROOT, "dist")}
OutputBaseFilename=Avel-Bundle-Windows-Setup
Compression=lzma2/max
SolidCompression=yes
WizardStyle=modern
CloseApplications=no

[Languages]
Name: "en"; MessagesFile: "compiler:Default.isl"
Name: "ru"; MessagesFile: "compiler:Languages\\Russian.isl"

[Messages]
en.WelcomeLabel2=This will install the Avel plugins (VST3) into%n%nC:\\Program Files\\Common Files\\VST3%n%nOn the next pages you can untick plugins you don't need. Close your DAW before continuing.
ru.WelcomeLabel2=Будут установлены плагины Avel (VST3) в папку%n%nC:\\Program Files\\Common Files\\VST3%n%nНа следующей странице можно снять галочки с ненужных плагинов. Перед продолжением закройте DAW.
en.FinishedLabel=Avel plugins are installed. Start your DAW and rescan plugins.
ru.FinishedLabel=Плагины Avel установлены. Запустите DAW и пересканируйте плагины.

[Types]
Name: "full"; Description: "{{cm:FullInstallation}}"
Name: "custom"; Description: "{{cm:CustomInstallation}}"; Flags: iscustom

[Components]
{chr(10).join(comps)}

[InstallDelete]
; remove files of an older version inside each plugin bundle
{chr(10).join(deletes)}

[Files]
{chr(10).join(files)}

[UninstallDelete]
{chr(10).join(deletes)}
"""
    # UTF-8 with BOM so Inno Setup reads the em dashes and Cyrillic correctly
    with open(os.path.join(out, "AvelBundle.iss"), "w", encoding="utf-8-sig") as f:
        f.write(iss)


def notes(art, out_file):
    plugins, version = load()
    repo = "https://github.com/johntok0001"
    rows = []
    for p in plugins:
        v, sha = info(art, p)
        rows.append(f"| [{p['product']}]({repo}/{p['repo']}) | {p['about']} | {v} | `{sha[:7]}` |")
    text = f"""Все плагины Avel в одном установщике. / All Avel plugins in one installer.

**macOS** — `Avel-Bundle-macOS.pkg` (VST3 + Audio Unit, Apple Silicon и Intel). Двойной клик → Продолжить → Установить. Кнопка «Настроить» позволяет снять галочки с ненужных плагинов.
Если macOS не даёт открыть: Системные настройки → Конфиденциальность и безопасность → «Всё равно открыть».

**Windows** — `Avel-Bundle-Windows-Setup.exe` (VST3, 64-bit). Если появится «Windows защитила ваш компьютер»: Подробнее → Выполнить в любом случае.

`Avel-Bundle.zip` — оба установщика одним архивом.

После установки перезапустите DAW и пересканируйте плагины.

| Plugin | | Version | Commit |
|---|---|---|---|
{chr(10).join(rows)}

<!-- manifest: {",".join(info(art, p)[1] for p in plugins)} -->
"""
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    if len(sys.argv) != 4 or sys.argv[1] not in ("mac", "windows", "notes"):
        sys.exit(__doc__)
    {"mac": mac, "windows": windows, "notes": notes}[sys.argv[1]](sys.argv[2], sys.argv[3])
